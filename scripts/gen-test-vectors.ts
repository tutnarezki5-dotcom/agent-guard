/**
 * Writes contracts/test-vectors.json: real AgentGuard authorizations
 * (fields, exact message, ed25519 signature, public key) produced by the
 * TypeScript signer. The Rust tests check they build the same message;
 * the same file can drive an on-chain test of `env::ed25519_verify`.
 *
 * Uses a FIXED, PUBLIC test seed. Never use this key for anything real.
 */
import { writeFileSync } from "node:fs";
import { GuardSigner, authorizationMessage, verifyMessage } from "../packages/guard/src/index.ts";

const TEST_SEED = Buffer.alloc(32, 7).toString("base64");
const signer = GuardSigner.fromSeedBase64(TEST_SEED);

const cases = [
  { contract_id: "vault.agentguard.testnet", mandate_id: "m_api_access_01", receiver: "weather-api.testnet", amount_yocto: "200000000000000000000000", nonce: 1, expires_at_ms: 1793700000000, input_hash: "a".repeat(64) },
  { contract_id: "vault.agentguard.testnet", mandate_id: "m-2.b_c", receiver: "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef", amount_yocto: "340282366920938463463374607431768211455", nonce: 18446744073709551, expires_at_ms: 1, input_hash: "0f".repeat(32) },
  { contract_id: "v.near", mandate_id: "x", receiver: "a.b.c.testnet", amount_yocto: "1", nonce: 0, expires_at_ms: 0, input_hash: "deadbeef" },
];

const vectors = cases.map((c) => {
  const message = authorizationMessage(c);
  const signature = signer.signMessage(message);
  if (!verifyMessage(message, signature, signer.publicKeyNear)) throw new Error("self-check failed");
  return { ...c, message, signature_base64: signature };
});

writeFileSync(
  new URL("../contracts/test-vectors.json", import.meta.url),
  `${JSON.stringify({ note: "Generated by scripts/gen-test-vectors.ts with a PUBLIC test seed (32 bytes of 0x07). Do not use for real funds.", guard_public_key: signer.publicKeyNear, vectors }, null, 2)}\n`,
);
console.log(`wrote ${vectors.length} vectors, guard key ${signer.publicKeyNear}`);
